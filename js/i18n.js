const LANG_ORDER = Object.keys(LANG_META);

let currentLang = (function detectLang() {
  const saved = localStorage.getItem('candy-lang');
  if (saved && LANG_META[saved]) return saved;
  if (typeof navigator !== 'undefined' && navigator.language) {
    const nav = navigator.language.toLowerCase();
    const found = LANG_ORDER.find(code => nav === code.toLowerCase() || nav.startsWith(code.toLowerCase() + '-'));
    if (found) return found;
  }
  return 'zh-CN';
})();

function setLang(code) {
  if (!LANG_META[code]) return;
  currentLang = code;
  localStorage.setItem('candy-lang', code);
}

function t(key, vars) {
  const dict = I18N[currentLang] || I18N['en'] || {};
  let str = dict[key];
  if (str === undefined) str = (I18N['en'] && I18N['en'][key]) || key;
  if (vars) {
    for (const k in vars) {
      str = str.split('{' + k + '}').join(String(vars[k]));
    }
  }
  return str;
}
